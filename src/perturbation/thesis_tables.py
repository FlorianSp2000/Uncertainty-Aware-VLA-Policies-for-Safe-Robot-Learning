def detector_comparison(res, ens, cls, clip, out: Path) -> None:
    blocks = detector_blocks(ens, cls, clip, encoder=True, clip_scores=("clip_alignment", "clip_knn"),
                             encoder_scores=("enc_knn",), sole_relabeling=False)
    image_only = ("clip_knn",)  # scores the image alone: undefined under a changed instruction
    cols = [(stack(*title_case(condition_name(c)).rsplit(" ", 1)),
             lambda r, rd, c=c, s=s: None if (c != "inpaint" and rd in image_only) else auc(res[s][r], c, "both", rd),
             "auroc") for s, c in (("val200", "lang_swap_train"), ("val200", "lang_swap_near"), ("inpainting258", "inpaint"))]
    # detector_table looks rows up in one result set; cells here pick their set per column, so pass labels through
    t = detector_table({lab: lab for _, rows in blocks for lab, _, _ in rows}, blocks, cols, None,
                       marked=lambda j: True, unranked=image_only)
    write(out, t, "AUROC of SayNo and the baselines under the three perturbations. CLIP novelty scores the image "
          "alone, so it is undefined under relabeling and, under object removal, responds to the re-rendered image "
          "rather than the removed object (Appendix~\\ref{sec:app-object-removal-controls}); it is not ranked. " + legend("per column"),
          "tab:bf-detector-comparison",
          [P_AUROC, P_BOTH, P_RELABEL, P_RHO, P_DETECTORS, f"novelty: k = {KNN_K}; Mahalanobis rows, ResNet--MUSE runs "
           "1-2 and per-dataset values in the appendix tables", "comparison group: all ranked detector rows in one column"])


P_OPERATING_POINT = ("threshold: split conformal (1 - alpha) quantile, alpha = {alpha}, of the average-of-both-frames "
                     "score on the originals of a random half of the pairs; recall = TPR on the perturbed inputs of the "
                     "other half; 200 random halves, seed 0; the realised false-alarm rate (mean over halves) rounds to "
                     "alpha for every row (asserted by the generator)")


def object_removal_recall(res, blocks, alpha: str):
    """Cell fn (model result, score key) -> split-half operating point of object removal at `alpha`;
    first asserts every row's realised false-alarm rate rounds to alpha."""
    op = lambda r, rd: r["operating_point"]["readouts"][rd]["split_half_test_originals"][alpha]
    for _, rows in blocks:
        for lab, rd, _ in rows:
            fpr = op(res["inpainting258"][lab], rd)["fpr_mean"]
            if shown(fpr) != shown(float(alpha)):
                raise ValueError(f"{lab}/{rd}: realised false-alarm rate {fpr:.3f} does not round to alpha {alpha}")
    return op


def object_removal_operating_point(res, ens, cls, clip, alpha: str, out: Path) -> None:
    blocks = detector_blocks(ens, cls, clip, encoder=True, clip_scores=("clip_mahalanobis", "clip_knn", "clip_alignment"),
                             sole_relabeling=True)
    a = float(alpha)
    frame_cols = [(t, lambda r, rd, f=f: auc(r, "inpaint", f, rd), "auroc") for f, t in
                  (("first", "Initial"), ("last", "Final"), ("both", "Average"))]
    op = object_removal_recall(res, blocks, alpha)
    t = detector_table(res["inpainting258"], blocks, frame_cols + [("Recall", op, "op")],
                       [("", 1), ("AUROC", 3), (stack(rf"{100 * a:.0f}\,\% of Originals", "Flagged"), 1)],
                       marked=lambda j: True)
    write(out, t, "AUROC of every detector under object removal, and the share of perturbed inputs flagged at a "
          f"threshold that flags {100 * a:.0f}\\,\\% of the originals (trajectory-level false-alarm rate). "
          f"{counts(res, 'inpainting258')}, each pair checked by eye. Recall: mean and, in "
          "parentheses, range over 200 random halves, the threshold being calibrated on the originals of one half "
          "and applied to the other. " + legend("per column", pm=False), "tab:bf-inpainting-operating-point",
          [P_AUROC, P_BOTH, P_RHO, P_DETECTORS, P_OPERATING_POINT.format(alpha=alpha),
           "comparison group: all detector rows in one column"])


def controls(res, ens, cls, clip, masks: dict, alpha: str, out: Path) -> None:
    blocks = detector_blocks(ens, cls, clip, encoder=True, clip_scores=("clip_mahalanobis", "clip_knn", "clip_alignment"),
                             sole_relabeling=True)
    pct = round(100 * float(alpha))
    cols = [(stack(*title_case(condition_name(c)).rsplit(" ", 1)), lambda r, rd, c=c: auc(r, c, "both", rd), "auroc")
            for c in CONTROLS] + [(stack(rf"Recall at {pct}\,\%", "of Originals", "Flagged"),
                                   object_removal_recall(res, blocks, alpha), "op")]
    t = detector_table(res["inpainting258"], blocks, cols, None,
                       marked=lambda j: j == len(CONTROLS) or CONTROLS[j] in MARKED_CONTROLS)
    write(out, t, "AUROC of every detector under object removal and three controls that separate the removed object "
          "from image artifacts (definitions in Appendix~\\ref{sec:app-object-removal-controls}), and the recall "
          f"under object removal at a threshold that flags {pct}\\,\\% of the originals. "
          f"{counts(res, 'inpainting258')}. Recall: mean and, in parentheses, range over 200 random halves of "
          "the trajectories. "
          + legend("per column for object removal, the edit-region control and the recall, where a detector of the "
                   "object should score high", pm=False),
          "tab:bf-inpainting-controls",
          [P_AUROC, P_BOTH, P_RHO, P_DETECTORS, P_OPERATING_POINT.format(alpha=alpha),
           f"edit region: pixels with max-channel |inpainted - original| > {masks['mask_threshold']}, dilated 16 px "
           f"(median {100 * masks['area_median']:.1f} % of the frame); edit-region control: inpainted inside the region, "
           "original outside; background control: original inside, inpainted outside; re-encoding control: original "
           f"JPEG-encoded at quality {masks['jpeg_quality']}, chosen to match the median per-pixel change of object "
           f"removal ({masks['median_delta']:.0f} grey levels)",
           "comparison group: all detector rows in the object-removal, edit-region and recall columns; background "
           "and re-encoding columns not marked (a detector of the object should stay at 0.5 there)"],
          size=NARROW)


def encoder_novelty(res, ens, spearman: dict, out: Path) -> None:
    conds = ([("inpainting258", c) for c in CONTROLS] + [("val200", c) for c in MAIN_LANG])
    marked_conds = set(MARKED_CONTROLS) | set(MAIN_LANG)
    body = []
    for g, (s, c) in enumerate(conds):
        body.append(group_row(condition_name(c), 6, g == 0))
        for lab in ens:
            rs = res[s]
            cells = [auc(rs[lab], c, "both", "spread"), auc(rs[f"{lab} | enc_mahalanobis"], c, "both", "enc_mahalanobis"),
                     auc(rs[f"{lab} | enc_knn"], c, "both", "enc_knn")]
            marks = ranks([value(x) for x in cells], digits=DIGITS) if c in marked_conds else [None] * 3
            rho = [spearman[s][lab][c][m] for m in ("enc_mahalanobis", "enc_knn")]
            body.append([indent(model_name(lab))] + [pm(x, m) for x, m in zip(cells, marks)] +
                        [pm(x, None, signed=True, key="rho") for x in rho])
    knn = "$k$-NN"  # k = KNN_K is stated once in the thesis appendix, not in every label
    t = booktabs(["SayNo Variant", "$\\sigma_Q$", "Mahalanobis", knn, "Mahalanobis", knn], body,
                 align=colspec(5), group_header=[("", 1), ("AUROC", 3),
                                              (stack("Spearman Correlation", "with Change in $\\sigma_Q$"), 2)])
    write(out, t, "Ensemble disagreement $\\sigma_Q$ compared with novelty measured in SayNo's own encoder features "
          f"(Mahalanobis and {knn} distance). The AUROC columns score each perturbation; the last two columns give "
          "the Spearman correlation, across trajectories, between the change of a novelty score and the change of "
          "$\\sigma_Q$ from the original to the perturbed input. "
          f"Object removal and controls on {counts(res, 'inpainting258')}, relabeling on "
          f"{counts(res, 'val200')} of the test split. "
          + legend("among the three AUROC columns of a row, except for the background and re-encoding controls"),
          "tab:bf-encoder-novelty",
          [P_AUROC, P_BOTH, P_RELABEL, P_RHO, P_DETECTORS,
           "Spearman rho across trajectories between paired shifts (perturbed - original) of the novelty score and of "
           "sigma_Q, both at the average of both frames; +- from a bootstrap over trajectories (2000 resamples)",
           "comparison group: sigma_Q vs the two encoder-novelty AUROCs in one row; rho columns and the background / "
           "re-encoding rows not marked"],
          size=NARROW)


def classifier_parts(lab: str) -> tuple[str, str]:
    """'ResNet--MUSE 1 (per trajectory)' -> ('ResNet--MUSE 1', 'per trajectory') for stacked headers."""
    name, sep, unit = lab.partition(" (")
    if not sep or not unit.endswith(")"):
        raise ValueError(f"classifier label must read 'NAME (RELABELING UNIT)', got {lab!r}")
    return name, unit[:-1]


