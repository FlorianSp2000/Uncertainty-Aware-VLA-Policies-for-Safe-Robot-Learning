def relabeling_frames(res, ens, out: Path) -> None:
    frames = ("first", "last", "both")
    body, g = [], 0
    ncol = 1 + len(ENS_SCORES) * len(frames)
    for lab in ens:
        r = res["val200"][lab]
        for c in LANG:
            name = condition_name(c)
            body.append(group_row(f"{model_name(lab)}: {name[0].lower()}{name[1:]}", ncol, g == 0))
            g += 1
            for d in (None, *DATASETS):
                row = [indent("All" if d is None else DATASETS[d])]
                for rd in ENS_SCORES:
                    cells = [auc(r, c, f, rd, d) for f in frames]
                    row += [pm(x, m) for x, m in zip(cells, ranks([value(x) for x in cells], digits=DIGITS))]
                body.append(row)
    t = booktabs(["Source Data"] + ["Initial", "Final", "Average"] * len(ENS_SCORES), body,
                 align=colspec(ncol - 1),
                 group_header=[("", 1)] + [(title_case(SCORE_NAMES[rd]), len(frames)) for rd in ENS_SCORES])
    write(out, t, "AUROC of ensemble disagreement and value score under counterfactual relabeling, per frame and "
          "per source dataset. Initial and final use one frame; average scores the member values $q_{k,t}$ averaged "
          "over both frames. "
          f"{counts(res, 'val200')} of the test split. " + legend("among the three frame choices of one score"),
          "tab:bf-langswap-frame", [P_AUROC, P_BOTH, P_RELABEL, P_RHO,
                                    "comparison group: initial / final / average of one score in one row"])


