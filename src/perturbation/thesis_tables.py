           "ResNet--MUSE: ResNet-34 + FiLM image encoder, MUSE language encoder, same family as SayNo; Octo: "
           "pretrained Octo-small, full finetune; per trajectory: one relabeled instruction for a whole training "
           "trajectory; per sample: fresh relabeling per training sample; relabeling implementation of the "
