# ------------------------------------------------------------------------------------------ cells

def shown(v: float) -> float:
    return round(v, DIGITS)


def _num(v: float, mark: str | None, signed: bool = False) -> str:
    v = 0.0 if shown(v) == 0 else v  # no "-0.00"
    s = f"{v:+.{DIGITS}f}" if signed else f"{v:.{DIGITS}f}"
    return {None: s, "bold": r"\mathbf{" + s + "}", "underline": r"\underline{" + s + "}"}[mark]


def pm(cell: dict | None, mark: str | None = None, signed: bool = False, key: str = "auroc") -> str:
    """Value +- half-width of its 95 % interval, math mode."""
    if cell is None:
        return "--"
    lo, hi = cell["ci95"]
    return f"${_num(cell[key], mark, signed)}" + r"{\scriptstyle\,\pm\," + f"{(hi - lo) / 2:.{DIGITS}f}" + "}$"


def span(d: dict | None, mark: str | None = None, mean="mean", lo="min", hi="max") -> str:
    """Mean with (min--max); the range is dropped when it is a single value."""
    if d is None:
        return "--"
    s = f"${_num(d[mean], mark)}"
    if shown(d[lo]) != shown(d[hi]):
        s += r"{\scriptstyle\,(" + f"{d[lo]:.{DIGITS}f}" + r"\text{--}" + f"{d[hi]:.{DIGITS}f})" + "}"
    return s + "$"


def value(cell: dict | None, key: str = "auroc") -> float | None:
    return None if cell is None else cell[key]


def legend(scope: str, pm: bool = True) -> str:
    """Closing caption sentence: the comparison group of the marks. What +- and the marks mean is
    stated once in the metrics paragraph of the thesis (Section 4.1), not per caption; `pm` is kept
    for the call sites."""
    return f"Marks compare values {scope}."


def colspec(n: int) -> str:
    """Label column + n centred columns, no outer padding."""
    return "@{}l" + "c" * n + "@{}"


def group_row(text: str, ncol: int, first: bool) -> str:
    return ("" if first else "\\addlinespace[3pt]\n") + r"\multicolumn{" + str(ncol) + r"}{@{}l}{\textit{" + text + r"}} \\"


def indent(s: str) -> str:
    return r"\hspace{0.7em}" + s


def auc(r: dict, cond: str, frame: str, rd: str, ds: str | None = None) -> dict | None:
    table = r["auroc"] if ds is None else r["auroc_by_dataset"][ds]
    return table.get(cond, {}).get(frame, {}).get(rd)


def counts(res: dict, s: str) -> str:
    r = next(iter(res[s].values()))
    by = ", ".join(f"{k} {DATASETS[d]}" for d, k in r["n_by_dataset"].items())
    return f"{r['n_trajectories']} trajectories ({by})"


def write(out: Path, tabular: str, caption: str, label: str, notes: list[str], generator: str = GENERATOR,
          size: str = SIZE) -> None:
    write_table(out, [tabular], caption, label, size=size, comment="\n".join([f"{out.name} -- {generator}"] + notes))


def marked_rows(cells: list[list[dict | None]], by: str, eligible=None, key: str = "auroc") -> list[list[str | None]]:
    """Marks for a grid of cells, ranked per column (`by='col'`) or per row (`by='row'`);
    `eligible(i, j)` excludes cells from ranking."""
    n, m = len(cells), len(cells[0])
    ok = eligible or (lambda i, j: True)
    vals = [[value(cells[i][j], key) if ok(i, j) else None for j in range(m)] for i in range(n)]
    marks = [[None] * m for _ in range(n)]
    if by == "row":
        for i in range(n):
            marks[i] = ranks(vals[i], digits=DIGITS)
    elif by == "col":
        for j in range(m):
            col = ranks([vals[i][j] for i in range(n)], digits=DIGITS)
            for i in range(n):
                marks[i][j] = col[i]
    else:
        raise ValueError(by)
    return marks


# ------------------------------------------------------------------------------ detector families

def classifier_group(sole_relabeling: bool) -> str:
    """Header of the classifier rows; names their training relabeling as condition_name does."""
    return f"Classifiers (trained with {condition_name('lang_swap_train', sole_relabeling).lower()})"


def detector_blocks(ens: list[str], cls: list[str], clip: dict[str, str], encoder: bool,
                    clip_scores: tuple[str, ...], sole_relabeling: bool,
                    encoder_scores: tuple[str, ...] = ("enc_mahalanobis", "enc_knn")) -> list[tuple[str, list[tuple[str, str, str]]]]:
    """[(group label, [(model label, score key, row name)])]: SayNo variants, their encoder novelty,
    classifiers, CLIP -- the one row order of every detector table. `sole_relabeling`: the table shows
    no relabeling variant next to the classifiers' training one (names it as condition_name does)."""
    blocks = [(model_name(lab), [(lab, rd, SCORE_NAMES[rd]) for rd in ENS_SCORES]) for lab in ens]
    if encoder and len(encoder_scores) == 1:
        rd = encoder_scores[0]
        blocks.append((f"Encoder novelty, {SCORE_NAMES[rd]}", [(f"{lab} | {rd}", rd, model_name(lab)) for lab in ens]))
    elif encoder:
        blocks += [(f"Encoder novelty, {model_name(lab)}", [(f"{lab} | {rd}", rd, SCORE_NAMES[rd]) for rd in encoder_scores])
                   for lab in ens]
    blocks.append((classifier_group(sole_relabeling), [(lab, "p_infeasible", model_name(lab)) for lab in cls]))
    blocks.append((clip["label"], [(clip[rd], rd, SCORE_NAMES[rd]) for rd in clip_scores]))
    return blocks


def detector_table(res_set: dict, blocks, columns, head_groups, marked, unranked: tuple[str, ...] = ()) -> str:
    """columns: [(header, fn(model result, score key) -> cell, kind)], kind 'auroc' (value +- CI
    half-width) or 'op' (split-half recall, mean (min--max)); marked(j): column j is ranked
    across all detector rows."""
    flat = [(lab, rd, name) for _, rows in blocks for lab, rd, name in rows]
    cells = [[fn(res_set[lab], rd) for _, fn, _ in columns] for lab, rd, _ in flat]
    key = {"auroc": "auroc", "op": "tpr_mean"}
    marks = [[None] * len(columns) for _ in flat]
    for j, (_, _, kind) in enumerate(columns):
        if marked(j):
            eligible = [rd not in unranked for _, rd, _ in flat]
            for i, m in enumerate(ranks([value(row[j], key[kind]) for row in cells], eligible=eligible, digits=DIGITS)):
                marks[i][j] = m
    fmt = {"auroc": lambda c, m: pm(c, m), "op": lambda c, m: span(c, m, "tpr_mean", "tpr_min", "tpr_max")}
    ncol = 1 + len(columns)
    body, i = [], 0
    for g, (group, rows) in enumerate(blocks):
        body.append(group_row(group, ncol, g == 0))
        for _, _, name in rows:
            body.append([indent(name)] + [fmt[kind](c, m) for (_, _, kind), c, m in zip(columns, cells[i], marks[i])])
            i += 1
    return booktabs(["Detector"] + [h for h, _, _ in columns], body, align=colspec(len(columns)),
                    group_header=head_groups)


