def reward_ablation(res, labels, reference: str, out: Path) -> None:
    cols = [("val200", c) for c in LANG] + [("val200", "act_far"), ("inpainting258", "inpaint")]
    body, ncol = [], 1 + len(cols)
    k_abl = {res["val200"][lab]["n_members"] for lab in labels}
    if len(k_abl) != 1:
        raise ValueError(f"ablation ensembles differ in size: {k_abl}")
    k_ref = res["val200"][reference]["n_members"]
    for g, rd in enumerate(ENS_SCORES):
        cells = [[auc(res[s][lab], c, "both", rd) for s, c in cols] for lab in labels + [reference]]
        marks = marked_rows(cells, "col", lambda i, j: i < len(labels))
        body.append(group_row(SCORE_NAMES[rd], ncol, g == 0))
        names = [model_name(lab) for lab in labels] + [f"Reference, $K = {k_ref}$"]
        body += [[indent(n)] + [pm(c, m) for c, m in zip(cr, mr)] for n, cr, mr in zip(names, cells, marks)]
    head = [stack("Random", "Relabeling"), stack("Random", "(Test Pool)"), stack("Nearest-", "Instruction"),
            stack("Far", "Action"), stack("Object", "Removal")]
    t = booktabs(["Training"] + head, body, align=colspec(len(cols)))
    k = next(iter(k_abl))
    write(out, t, f"AUROC of SayNo variants with $K = {k}$ members trained on Bridge only, with and without a terminal "
          "penalty on relabeled training samples. The reference row of each block is the "
          f"{k_ref}-member {model_name(reference)} trained on Bridge and Fractal, for scale. "
          f"Relabeling and far action on {counts(res, 'val200')} of the test split, object removal on "
          f"{counts(res, 'inpainting258')}. " + legend(f"per column among the $K = {k}$ variants"),
          "tab:bf-reward-ablation-per-sample",
          [P_AUROC, P_BOTH, P_RELABEL,
           f"ablations: {k}-member ensembles, 200k steps, Bridge only; penalty: terminal reward of relabeled training "
           "trajectories (rho = 5 %), printed as SayNo-CR, penalty ...; SayNo: same recipe without relabeled samples",
           "comparison group: the five Bridge-only variants in one column and score block; reference row not marked"])


def latency(path: Path, out: Path) -> dict:
    lat = json.loads(path.read_text(encoding="utf-8"))
    body = [group_row("SayNo critic ensemble, GPU", 5, True)]
    body += [[indent(str(c["members"])), str(c["rows"]), f"{c['median_ms']:.1f}", f"{c['p90_ms']:.1f}",
              f"{c['hz_at_median']:.0f}"] for c in lat["critic"]]
    mu = lat["muse_encode_one_instruction_cpu"]
    body += [group_row("MUSE language encoder, CPU, one instruction", 5, False),
             [indent("--"), "--", f"{mu['median_ms']:.1f}", f"{mu['p90_ms']:.1f}", f"{mu['hz_at_median']:.0f}"]]
    t = booktabs(["Members $K$", stack("Actions", "per Call"), stack("Median", "(ms)"), stack("90th Percentile", "(ms)"),
                  stack("Rate at", "Median (Hz)")], body, align=colspec(4))
    dev = lat["device"].replace("NVIDIA ", "NVIDIA~")
    write(out, t, f"Inference latency of the SayNo critic ensemble on one {dev} GPU for one observation and a number "
          "of candidate actions (more than one, e.g., when the candidates of a sampling policy are scored). The "
          "instruction embedding is computed once per instruction on the CPU and is not included in the critic rows. "
          "Median over timed calls; the rate is 1000 divided by the unrounded median.", "tab:bf-latency",
          [f"JAX {lat['jax']}, jit-compiled, one 256x256 image, {lat['n_calls']} timed calls after {lat['warmup']} "
           "warm-up; the image encoder is re-run for every action row (no shared encoding); rate = 1000 / median ms",
           "no marks: rows are configurations, not alternatives"])
    return lat


def clip_labels(clip_label: str) -> dict[str, str]:
    return {rd: f"{clip_label} | {rd}" for rd in ("clip_mahalanobis", "clip_knn", "clip_alignment")}


def encoder_labels(ens: list[str]) -> list[str]:
    return [f"{lab} | {rd}" for lab in ens for rd in ("enc_mahalanobis", "enc_knn")]


