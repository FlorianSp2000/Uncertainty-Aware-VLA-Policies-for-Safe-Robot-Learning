def _score_rows(res, ens, rds, out: Path, caption: str, label: str, group: str) -> None:
    """Rows: detection scores `rds` per SayNo variant; columns: random and nearest-instruction relabeling,
    object removal; marks within one variant and column."""
    cols = [("val200", c) for c in MAIN_LANG] + [("inpainting258", "inpaint")]
    body = []
    for g, lab in enumerate(ens):
        cells = [[auc(res[s][lab], c, "both", rd) for s, c in cols] for rd in rds]
        marks = marked_rows(cells, "col")
        body.append(group_row(model_name(lab), 1 + len(cols), g == 0))
        body += [[indent(SCORE_NAMES[rd])] + [pm(c, m) for c, m in zip(cr, mr)] for rd, cr, mr in zip(rds, cells, marks)]
    t = booktabs(["Detection Score"] + [stack(*title_case(condition_name(c)).rsplit(" ", 1)) for _, c in cols], body,
                 align=colspec(len(cols)))
    write(out, t, caption + legend("per model and perturbation"), label,
          [P_AUROC, Z_NOTE, P_RELABEL, P_RHO, f"comparison group: {group} of one SayNo variant in one column"])


