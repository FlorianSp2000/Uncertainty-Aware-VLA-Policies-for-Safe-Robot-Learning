def write_all(res: dict, spearman: dict, masks: dict, roles: dict, latency_json: Path, out: Path) -> dict:
    """Every thesis table into `out`. roles: main_ensembles, classifiers, classifier_notes, ablations,
    reference_ensemble, clip_label, table_alpha, actions. Returns the latency record."""
    ens, cls_all = roles["main_ensembles"], roles["classifiers"]
    if not set(MAIN_CLASSIFIERS) <= set(cls_all):
        raise ValueError(f"MAIN_CLASSIFIERS {MAIN_CLASSIFIERS} not all in the analysis classifiers {cls_all}")
    cls = list(MAIN_CLASSIFIERS)
    clip = {**clip_labels(roles["clip_label"]), "label": roles["clip_label"]}
    time_normalised(res, ens, out / FILES["time_normalised"])
    time_normalised_variants(res, ens, out / FILES["time_normalised_variants"])
    member_count(res, ens, out / FILES["member_count"])
    action_perturbations(res, ens, roles["actions"], out / FILES["actions"])
    relabeling_frames(res, ens, out / FILES["frames"])
    random_vs_nearest(res, ens, cls, clip, out / FILES["nearest"])
    detector_comparison(res, ens, cls, clip, out / FILES["all"])
    object_removal_operating_point(res, ens, cls, clip, roles["table_alpha"], out / FILES["operating_point"])
    controls(res, ens, cls, clip, masks, roles["table_alpha"], out / FILES["controls"])
    encoder_novelty(res, ens, spearman, out / FILES["encoder"])
    classifier_variants(res, cls_all, roles["classifier_notes"], out / FILES["classifiers"])
    reward_ablation(res, roles["ablations"], roles["reference_ensemble"], out / FILES["reward"])
    return latency(latency_json, out / FILES["latency"])


